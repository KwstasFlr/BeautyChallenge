const normalizeOfficialQuestion=value=>value
  .normalize('NFD').replace(/[\u0300-\u036f]/g,'')
  .toLowerCase().replace(/[«»“”"'΄’.,:;–—\-()]/g,' ')
  .replace(/\s+/g,' ').trim();

function parseOfficialCatalogue(text){
  const theoryStart=text.indexOf('ΟΜΑΔΑ Α. ΓΕΝΙΚΕΣ ΕΡΩΤΗΣΕΙΣ',text.indexOf('Σελίδα 3 από 15'));
  const practicalStart=text.indexOf('4. Πρακτικό Μέρος',theoryStart);
  const theory=text.slice(theoryStart,practicalStart)
    .replace(/^Ε\.Ο\.Π\.Π\.Ε\.Π\..*$/gm,'')
    .replace(/^ΤΕΧΝΙΚΟΣ ΑΙΣΘΗΤΙΚΗΣ ΤΕΧΝΗΣ ΚΑΙ ΜΑΚΙΓΙΑΖ.*$/gm,'')
    .replace(/^Σελίδα \d+ από \d+.*$/gm,'');
  const groupBIndex=theory.indexOf('ΟΜΑΔΑ Β. ΕΙΔΙΚΕΣ ΕΡΩΤΗΣΕΙΣ');
  const groups=[
    ['Ομάδα Α',theory.slice(theory.indexOf('\n',0),groupBIndex)],
    ['Ομάδα Β',theory.slice(groupBIndex+'ΟΜΑΔΑ Β. ΕΙΔΙΚΕΣ ΕΡΩΤΗΣΕΙΣ'.length)]
  ];
  const curated=new Map(officialBank.map(item=>[normalizeOfficialQuestion(item[1]),item]));
  const result=[];

  groups.forEach(([group,content])=>{
    const matches=[...content.matchAll(/^\s*(\d+)\.\s+(.+?)(?=^\s*\d+\.\s+|\s*$)/gms)];
    matches.forEach(match=>{
      const question=match[2].replace(/\s+/g,' ').trim();
      const key=normalizeOfficialQuestion(question);
      const reviewed=curated.get(key);
      result.push(reviewed||[`${group} · ΕΟΠΠΕΠ`,question,null,null]);
    });
  });

  return result.length>150?result:officialBank;
}

