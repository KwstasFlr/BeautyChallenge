function dailyEntry(date=new Date()){
  const parts=new Intl.DateTimeFormat('en-GB',{
    timeZone:'Europe/Athens',
    year:'numeric',
    month:'numeric',
    day:'numeric'
  }).formatToParts(date);

  const part=type=>Number(parts.find(p=>p.type===type).value);
  const year=part('year');
  const month=part('month');
  const day=part('day');

  const index=Math.floor(
    (Date.UTC(year,month-1,day)-Date.UTC(year,0,1))/86400000
  );

  return{
    key:`${year}-${month}-${day}`,
    index,
    tip:dailyTips[index%dailyTips.length],
    quote:dailyQuotes[index%dailyQuotes.length]
  };
}

const dailyChallenges=Array.from({length:365},(_,index)=>{
  const q=bank[index%bank.length];
  const cycle=Math.floor(index/bank.length);
  const sameTopic=bank.filter((item,itemIndex)=>
    item[0]===q[0]&&itemIndex!==index%bank.length
  );
  const fallback=bank.filter(item=>item!==q&&!sameTopic.includes(item));
  const candidates=sameTopic.length>=3?sameTopic:[...sameTopic,...fallback];
  const others=[0,1,2].map(offset=>
    candidates[(index*7+offset*11)%candidates.length]
  );

  if(cycle%3===1){
    return{
      topic:q[0],
      question:`Τι σημαίνει στην πράξη «${q[2][0]}»;`,
      answers:[q[3],...others.map(item=>item[3])],
      explanation:q[3]
    };
  }

  if(cycle%3===2){
    return{
      topic:q[0],
      question:`Σε ποια ερώτηση ταιριάζει η απάντηση «${q[2][0]}»;`,
      answers:[q[1],...others.map(item=>item[1])],
      explanation:q[3]
    };
  }

  return{topic:q[0],question:q[1],answers:q[2],explanation:q[3]};
});

let dailyChallengeAnswer=null;
const DAILY_CHALLENGE_STATE_KEY='beauty-daily-challenge-v1';

function savedDailyChallengeAnswer(today){
  try{
    const saved=JSON.parse(localStorage.getItem(DAILY_CHALLENGE_STATE_KEY));
    return saved?.day===today.key&&Number.isInteger(saved.answer)&&saved.answer>=0&&saved.answer<=3
      ?saved.answer
      :null;
  }catch{
    return null;
  }
}

function dailyChallengeOrder(dayIndex){
  const order=[0,1,2,3];
  let seed=dayIndex+1;
  for(let i=order.length-1;i>0;i--){
    seed=(seed*1664525+1013904223)>>>0;
    const j=seed%(i+1);
    [order[i],order[j]]=[order[j],order[i]];
  }
  return order;
}

function showDailyChallengeResult(challenge){
  const card=$('#dailyChallengeCard');
  if(!card||dailyChallengeAnswer===null)return;

  card.querySelectorAll('[data-daily-answer]').forEach(option=>{
    const answer=Number(option.dataset.dailyAnswer);
    option.disabled=true;
    if(answer===0)option.classList.add('is-correct');
    if(answer===dailyChallengeAnswer&&answer!==0)option.classList.add('is-wrong');
  });

  card.querySelector('.daily-challenge-feedback').innerHTML=`
    <strong>${dailyChallengeAnswer===0?'Σωστά!':'Η σωστή απάντηση φαίνεται με πράσινο.'}</strong><br>
    ${esc(challenge.explanation)}`;
}

function renderDailyChallenge(today){
  const challenge=dailyChallenges[today.index%dailyChallenges.length];
  const card=$('#dailyChallengeCard');
  if(!card)return;

  $('#dailyChallengeTopic').textContent=challenge.topic;
  $('#dailyChallengeTitle').textContent=challenge.question;
  const order=dailyChallengeOrder(today.index);
  card.innerHTML=`
    <div class="daily-challenge-options">
      ${order.map(answer=>`
        <button class="daily-challenge-option" data-daily-answer="${answer}">
          ${esc(challenge.answers[answer])}
        </button>
      `).join('')}
    </div>
    <div class="daily-challenge-feedback" aria-live="polite">
      Διάλεξε την απάντηση που θεωρείς σωστή.
    </div>`;

  dailyChallengeAnswer=savedDailyChallengeAnswer(today);
  showDailyChallengeResult(challenge);
}

$('#dailyChallengeCard')?.addEventListener('click',event=>{
  const button=event.target.closest('[data-daily-answer]');
  if(!button||dailyChallengeAnswer!==null)return;

  dailyChallengeAnswer=Number(button.dataset.dailyAnswer);
  const today=dailyEntry();
  const challenge=dailyChallenges[today.index%dailyChallenges.length];
  localStorage.setItem(DAILY_CHALLENGE_STATE_KEY,JSON.stringify({
    day:today.key,
    answer:dailyChallengeAnswer
  }));
  showDailyChallengeResult(challenge);
});

