function celebrityMatch(answers){
  const sums=[0,0,0,0],counts=[0,0,0,0];

  answers.forEach((answer,i)=>{
    if(Number.isInteger(answer)&&answer>=0&&answer<4){
      sums[celebrityAxes[i]]+=answer;
      counts[celebrityAxes[i]]++;
    }
  });

  const levels=sums.map((sum,i)=>Math.round(sum/(counts[i]||1)));
  const ranked=celebrityNames.map(name=>({
    name,
    distance:publicStyleProfile(name).reduce((total,value,index)=>
      total+Math.pow(value-levels[index],2),0)
  })).sort((a,b)=>a.distance-b.distance||a.name.localeCompare(b.name));
  const closest=ranked.filter(item=>item.distance===ranked[0].distance);
  const hash=answers.reduce((value,answer,index)=>(value*7+(answer+1)*(index+3))>>>0,17);
  return{name:closest[hash%closest.length].name,levels};
}

