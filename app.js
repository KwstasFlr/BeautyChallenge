function create(mode){
  const personality=entertainment[mode];
  const count=mode==='exam'?state.examCount:mode==='sos'?8:10;
  const pool=bank.map((_,i)=>i).filter(i=>mode!=='sos'||bank[i][0]==='Σενάρια');
  const ids=personality?personality.questions.map((_,i)=>i):shuffle(pool).slice(0,count);
  return{
    id:Date.now()+'-'+Math.random(),mode,ids,
    orders:ids.map(()=>shuffle([0,1,2,3])),
    answers:ids.map(()=>null),locked:ids.map(()=>false),
    pos:0,done:false,deadline:mode==='exam'?Date.now()+ids.length*90000:null
  };
}

function finish(s){
  if(s.done)return;
  s.done=true;
  s.correct=entertainment[s.mode]?null:s.answers.filter(x=>x===0).length;
  if(!state.history.some(h=>h.id===s.id)){
    state.history.unshift({
      id:s.id,mode:s.mode,correct:s.correct,total:s.ids.length,
      finishedAt:Date.now(),snapshot:JSON.parse(JSON.stringify(s))
    });
  }
  save();
}

function checkExpiry(){
  const s=state.sessions.exam;
  if(s&&!s.done&&Date.now()>=s.deadline){finish(s);return true}
  return false;
}

function progress(){
  const h=state.history,scored=h.filter(x=>!entertainment[x.mode]);
  const total=scored.reduce((n,x)=>n+x.total,0);
  const correct=scored.reduce((n,x)=>n+x.correct,0);
  $('#rounds').textContent=h.length;
  $('#accuracy').textContent=total?Math.round(correct/total*100)+'%':'—';
  $('#recent').textContent=h.length?'Τελευταίο: '+names[h[0].mode]:'Δεν έχει ολοκληρωθεί ακόμη κάποιος γύρος.';
  $('#storage').textContent=notice||'Η πρόοδος αποθηκεύεται μόνο σε αυτόν τον browser.';
}

function clockText(s){
  const t=Math.max(0,Math.ceil((s.deadline-Date.now())/1000));
  return String(Math.floor(t/60)).padStart(2,'0')+':'+String(t%60).padStart(2,'0');
}

