(()=>{
  const ID='G-K25078MPVK';
  const CONSENT_KEY='beauty-analytics-consent-v1';

  const panel=$('#analyticsConsent');
  const settings=$('#analyticsSettings');
  const status=$('#analyticsStatus');

  const denied={
    analytics_storage:'denied',
    ad_storage:'denied',
    ad_user_data:'denied',
    ad_personalization:'denied'
  };

  let choice=null,loaded=false,returnFocus=null;

  try{
    const stored=JSON.parse(localStorage.getItem(CONSENT_KEY));
    if(
      stored&&
      stored.expires>Date.now()&&
      ['accepted','rejected'].includes(stored.value)
    ){
      choice=stored.value;
    }
  }catch{}

  window['ga-disable-'+ID]=choice!=='accepted';

  function remember(value){
    choice=value;
    try{
      localStorage.setItem(
        CONSENT_KEY,
        JSON.stringify({
          value,
          expires:Date.now()+180*86400000
        })
      );
    }catch{}
  }

  function enable(){
    if(!/^https?:$/.test(location.protocol))return;

    window['ga-disable-'+ID]=false;

    if(loaded){
      window.gtag('consent','update',{
        ...denied,
        analytics_storage:'granted'
      });
      return;
    }

    loaded=true;
    window.dataLayer=window.dataLayer||[];

    window.gtag=function(){
      window.dataLayer.push(arguments);
    };

    window.gtag('consent','default',denied);
    window.gtag('consent','update',{
      ...denied,
      analytics_storage:'granted'
    });
    window.gtag('js',new Date());

    let referrer='';
    try{
      if(document.referrer){
        referrer=new URL(document.referrer).origin;
      }
    }catch{}

    window.gtag('config',ID,{
      allow_google_signals:false,
      allow_ad_personalization_signals:false,
      page_location:location.origin+location.pathname,
      page_referrer:referrer,
      page_title:'BEAUTY CHALLENGE'
    });

    const script=document.createElement('script');
    script.async=true;
    script.src='https://www.googletagmanager.com/gtag/js?id='+ID;
    document.head.appendChild(script);
  }

  function disable(){
    window['ga-disable-'+ID]=true;

    if(loaded){
      window.gtag('consent','update',denied);
    }

    const parts=location.hostname.split('.');
    const domains=[''];

    for(let i=0;i<parts.length-1;i++){
      const domain=parts.slice(i).join('.');
      domains.push('; domain='+domain,'; domain=.'+domain);
    }

    for(const name of ['_ga','_ga_K25078MPVK']){
      for(const domain of domains){
        document.cookie=name+'=; Max-Age=0; path=/'+domain;
      }
    }
  }

  function label(){
    status.textContent=choice==='accepted'
      ?'Τα στατιστικά είναι ενεργοποιημένα.'
      :choice==='rejected'
        ?'Τα στατιστικά είναι απενεργοποιημένα.'
        :'Τα στατιστικά είναι προαιρετικά.';
  }

  function close(){
    panel.hidden=true;
    (returnFocus||settings).focus({preventScroll:true});
  }

  settings.addEventListener('click',()=>{
    returnFocus=document.activeElement;
    label();
    panel.hidden=false;
    $('#analyticsTitle').focus({preventScroll:true});
  });

  $('#acceptAnalytics').addEventListener('click',()=>{
    remember('accepted');
    enable();
    label();
    close();
  });

  $('#rejectAnalytics').addEventListener('click',()=>{
    remember('rejected');
    disable();
    label();
    close();
  });

  label();
  panel.hidden=choice!==null;

  if(choice==='accepted')enable();
})();
