  if(action==='restart'){
    delete state.sessions.exam;save();render();focusTitle($('#stage'));return;
  }
  if(action==='start'){
    state.sessions.exam=create('exam');save();render();focusTitle($('#stage'));return;
  }

  const s=state.sessions.exam;
  if(state.mode!=='exam'||!s||s.done)return;
