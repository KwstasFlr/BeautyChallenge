$('#stage').addEventListener('click',e=>{
  const b=e.target.closest('button');
  if(!b||b.disabled)return;

  if(checkExpiry()){
    render();
    return;
  }

  const action=b.dataset.action;

  if(b.hasAttribute('data-study')){
    studyPage=Math.max(
      0,
      Math.min(
        Math.ceil(bank.length/8)-1,
        studyPage+Number(b.dataset.study)
      )
    );
    study();
    focusTitle($('#stage'));
    return;
  }

  if(b.hasAttribute('data-record')){
    const h=state.history[Number(b.dataset.record)];
    if(h?.snapshot){
      $('#stage').innerHTML=
        '<button class="quiet" data-action="archiveBack">← Πίσω στο αρχείο</button>'+
        resultHTML(h.snapshot,'');
      focusTitle($('#stage'));
    }
    return;
  }

  if(action==='archiveBack'){
    archive();
    return;
  }

  if(action==='restart'){
    delete state.sessions.exam;
    save();
    render();
    focusTitle($('#stage'));
    return;
  }

  if(action==='start'){
    state.sessions.exam=create('exam');
    save();
    render();
    focusTitle($('#stage'));
    return;
  }

  const s=state.sessions.exam;
  if(state.mode!=='exam'||!s||s.done)return;

  if(b.hasAttribute('data-answer')){
    s.answers[s.pos]=Number(b.dataset.answer);
  }

  if(b.hasAttribute('data-jump')){
    s.pos=Number(b.dataset.jump);
  }

  if(action==='prev'){
    s.pos=Math.max(0,s.pos-1);
  }

  if(action==='next'){
    if(s.pos<s.ids.length-1){
      s.pos++;
    }else{
      const missing=s.answers.filter(a=>a===null).length;
      $('#confirmText').textContent=missing
        ?`${missing} ερωτήσεις δεν έχουν απαντηθεί και θα μετρήσουν ως μη σωστές. Θέλεις να ολοκληρώσεις;`
        :'Να ολοκληρωθεί η προσπάθεια και να εμφανιστεί η διόρθωση;';
      $('#confirm').showModal();
      return;
    }
  }

  save();
  render();

  if(b.hasAttribute('data-answer')){
    $('#stage').querySelector(`[data-answer="${b.dataset.answer}"]`)
      ?.focus({preventScroll:true});
  }else{
    focusTitle($('#stage'));
  }
});

