  if(celebritySignals.socialBright.has(name))profile[0]=3;
  if(celebritySignals.classic.has(name))profile[1]=0;
  if(celebritySignals.experimental.has(name))profile[1]=3;
  if(celebritySignals.grounded.has(name))profile[2]=0;
